  function getItem(id) {
    if (!id) return null;
    return items[id] || null;
  }

  function getRelated(item) {
    if (!item || !item.related) return [];
    return item.related
      .map(function (rid) {
        return items[rid];
      })
      .filter(Boolean);
  }

  function listByGroup(group, limit) {
    var list = Object.keys(items)
      .map(function (k) {
        return items[k];
      })
      .filter(function (it) {
        return it.group === group;
      });
    if (typeof limit === "number") list = list.slice(0, limit);
    return list;
  }

